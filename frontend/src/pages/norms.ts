/**
 * «Какая скорость печати считается нормальной» — страница под частый запрос.
 *
 * Цифры здесь не выдуманы: это диапазоны, на которые опираются тесты печати,
 * пересчитанные в знаки в минуту через принятое соотношение «слово = 5 символов»
 * (то же, что в services/metrics.py).
 */

import type { PageContext } from "../router";
import { icon } from "../ui/icons";

interface Level {
  wpm: string;
  cpm: string;
  name: string;
  note: string;
}

const LEVELS: Level[] = [
  { wpm: "до 20", cpm: "до 100", name: "поиск глазами", note: "набор двумя-четырьмя пальцами, взгляд на клавиатуре" },
  { wpm: "20–35", cpm: "100–175", name: "уверенный новичок", note: "клавиши знакомы, но руки ещё ищут их" },
  { wpm: "35–50", cpm: "175–250", name: "средний уровень", note: "сюда попадает большинство людей, работающих за компьютером" },
  { wpm: "50–70", cpm: "250–350", name: "хорошо", note: "печать не мешает думать, текст успевает за мыслью" },
  { wpm: "70–90", cpm: "350–450", name: "быстро", note: "уровень тех, кто печатает много и каждый день" },
  { wpm: "90–120", cpm: "450–600", name: "очень быстро", note: "верхняя часть таблиц на тестах печати" },
  { wpm: "120+", cpm: "600+", name: "редкость", note: "требует отдельных тренировок, а не просто опыта работы" },
];

export function normsPage({ container }: PageContext): void {
  const rows = LEVELS.map(
    (level) => `
      <tr>
        <td><b>${level.wpm}</b></td>
        <td>${level.cpm}</td>
        <td>${level.name}</td>
        <td class="sub">${level.note}</td>
      </tr>`,
  ).join("");

  container.innerHTML = `
    <div class="textPage">
      <div class="section">
        <h1 class="title">${icon("chart")} Какая скорость печати считается нормальной</h1>
        <p>
          Короткий ответ: <b>около 40 слов в минуту</b>. Это примерно 200 знаков
          и примерно столько показывает человек, который давно работает за
          компьютером, но специально печати не учился.
        </p>
        <p>
          Ответ подлиннее — ниже, потому что «нормально» зависит от того, зачем
          вы печатаете. Для переписки хватает и 30 слов в минуту. Для работы
          с текстом каждый день разница между 40 и 70 — это уже часы в неделю.
        </p>
      </div>

      <div class="section">
        <h2 class="title">${icon("crown")} Таблица уровней</h2>
        <!-- Обёртка обязательна: четыре колонки на телефоне шире экрана,
             и без неё горизонтально ехала бы вся страница -->
        <div class="tableScroll">
        <table class="table">
          <thead>
            <tr>
              <th>слов в минуту</th>
              <th>знаков в минуту</th>
              <th>уровень</th>
              <th>что это значит</th>
            </tr>
          </thead>
          <tbody>${rows}</tbody>
        </table>
        </div>
        <p class="sub">
          Знаки в минуту пересчитаны из слов по принятому соотношению
          «слово = 5 символов». Так считают все тесты печати, поэтому цифры
          сравнимы между сайтами.
        </p>
      </div>

      <div class="section">
        <h2 class="title">${icon("bolt")} Почему точность важнее скорости</h2>
        <p>
          Скорость без точности не имеет смысла: 80 слов в минуту при 85%
          точности — это текст, который придётся переписывать. Каждая опечатка
          стоит дороже, чем сэкономленные на ней доли секунды, потому что
          возврат к ошибке ломает темп.
        </p>
        <p>
          Разумный ориентир — <b>не ниже 95%</b>. Если точность проваливается,
          вы печатаете быстрее, чем умеете, и тренируете не тот навык.
          Сбросьте темп до того, при котором ошибок почти нет, и наращивайте
          скорость оттуда.
        </p>
      </div>

      <div class="section">
        <h2 class="title">${icon("keyboard")} От чего ещё зависит цифра</h2>
        <ul class="aboutList">
          <li>
            <b>Язык.</b> В русском слова в среднем длиннее английских, поэтому
            на одном и том же уровне навыка русский текст обычно даёт wpm ниже.
            Сравнивать имеет смысл только результаты на одном языке.
          </li>
          <li>
            <b>Пунктуация и цифры.</b> Знаки требуют shift и верхнего ряда —
            с ними скорость падает на 10–20% даже у опытных.
          </li>
          <li>
            <b>Длина теста.</b> На 15 секундах результат почти всегда выше:
            на минуте начинает сказываться усталость и разброс темпа.
          </li>
          <li>
            <b>Клавиатура.</b> Незнакомая раскладка или непривычный ход клавиш
            сбивают на несколько процентов, и это не показатель навыка.
          </li>
        </ul>
      </div>

      <div class="section">
        <h2 class="title">${icon("users")} Как узнать свою цифру</h2>
        <p>
          Один тест ничего не говорит: разброс между попытками у одного человека
          легко достигает 15%. Прогоните три-четыре теста по минуте и смотрите
          на среднее, а не на лучший результат.
        </p>
        <p>
          <a href="/" class="button">Проверить скорость</a>
          <a href="/guide">Как научиться печатать вслепую</a> ·
          <a href="/leaderboard">Рейтинг</a>
        </p>
      </div>
    </div>
  `;
}
